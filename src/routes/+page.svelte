        <h2 id="privacy-attack" class="text-5xl md:text-6xl">
            Privacy is under attack
        </h2>
        <div class="flex flex-col gap-4">
            <div class="basis-1/2">
                <p>
                    The free and open spread of various symmetric and asymmetric
                    encryption schemes was a huge win for privacy. As I already
                    mentioned, the basis of all democratic institutions is that
                    each individual is <b
                        >free to think and speak without fear of retaliation.</b
                    > Maybe not on the public subway while annoying the hell out
                    of everyone, but there must be a platform where this is possible.
                </p>
                <p>
                    Privacy is very sexy in the eyes of criminals, too. Entire
                    illegal economies thrive in the shadows of privacy, hiding
                    from police forces. I don't think there is a single illegal
                    activity that didn't benefit from the appearance of private
                    communication. From the perspective of secret agencies, E2EE
                    and the spread of these platforms were a matter of national
                    security. Given this desperate fight against illegal
                    activities and people <span
                        class="text-white bg-black border-b-2 border-white px-1"
                        >going dark</span
                    >, it is not surprising that a backdoor into these
                    privacy-preserving platforms is a wet dream for every agency
                    and government.
                </p>
                <p>
                    In particular, one criminal activity is constantly in the
                    spotlight of the media and political debates concerning
                    private messaging: the distribution of child sexual abuse
                    material (CSAM). It is rightfully a focused goal to
                    prosecute everyone involved in CSAM, and we can safely say
                    this is a common denominator in European society.
                </p>
                <p>
                    The narrative of the governments is that people who prefer
                    private communication are either a) terrorists or b) CSAM
                    distributors. That is the <i>casus belli</i> against the proliferation
                    of privacy. The first is convincing because people fear terrorists,
                    and the second is convincing because we naturally want to defend
                    our children.
                </p>
                <div
                    class="card bg-orange-300 mb-5 text-black dark:bg-orange-800 dark:text-white"
                >
                    <button class="btn bg-pink mb-3">1956</button>
                    <p>
                        During the 1956 uprising in Hungary, freedom fighters
                        fighting against the Soviet regime were <b
                            >all called terrorists.</b
                        >
                    </p>
                </div>
                <p>
                    You might think that mass surveillance doesn't affect you
                    because you don't have anything to hide, being a perfect,
                    law-abiding citizen. This is one of the first arguments
                    people bring up. As I already mentioned, privacy is not
                    about keeping secrets. It's about holding back anything YOU
                    decide to, because you have a RIGHT to control information
                    related to you. Secrets are made from data, but secrets are
                    highly dependent on time. Data about you might not be
                    criminalizing right now, but this can change at any time.
                    Your messages won't be judged by the present, but by the
                    system that reads them tomorrow. Who makes the laws deciding
                    what is right or wrong? Furthermore, do not think that you
                    are irrelevant. By definition, <b
                        >mass surveillance targets the general populace.</b
                    > A million average people hold way more political and economic
                    power than a dozen celebrities or politicians. To control the
                    masses, one needs to control the life of the average person who
                    makes up that mass.
                </p>
                <div
                    class="card bg-blue-300 mb-5 text-black dark:bg-blue-800 dark:text-white"
                >
                    <button class="btn bg-pink mb-3">UK</button>
                    <p>
                        12,000 arrests in 2023, United Kingdom, for "offensive"
                        posts.
                    </p>
                </div>
                <p>
                    The worst part isn't just that they want to breach privacy,
                    but the fact that you know they are doing it. The danger
                    comes from the fact that a surveilled person behaves
                    completely differently. People don't search for things they
                    normally would. They don't speak out or question things they
                    normally would. <span
                        class="bg-pink text-black border-b-2 border-black dark:border-white px-1"
                        >Humans become their own censors, self-policing
                        themselves due to the psychological effects of
                        surveillance.</span
                    >
                    The
                    <a
                        href="https://en.wikipedia.org/wiki/Panopticon"
                        target="_blank"
                        class="bg-yellow text-black border-b-3 border-black dark:border-white hover:bg-white p-1"
                        >Panopticon</a
                    > is a prison design first proposed by Jeremy Bentham, where
                    inmates become docile simply because of the ever-watching guard
                    tower.
                </p>
            </div>
            <div
                class="card bg-blue-600 mb-5 text-white dark:bg-blue-900 border-2 border-black dark:border-white"
            >
                <button class="btn bg-yellow text-black mb-3"
                    >Chat Control</button
                >
                <p
                    class="text-sm italic bg-yellow text-black border-b-3 border-black dark:border-white hover:bg-white p-2 inline-block mb-2"
                >
                    <a
                        href="https://www.patrick-breyer.de/en/posts/chat-control/"
                        target="_blank"
                        >based on the work of Patrick Breyer, digital activist,
                        former Member of EU Parliament</a
                    >
                </p>
                <p>
                    The EU Commission proposed to oblige providers to <b
                        >search all private chats, messages, and emails
                        automatically</b
                    > for suspicious content – generally and indiscriminately. The
                    stated aim: To prosecute child sexual exploitation material (CSEM).
                    The result: Mass surveillance by means of fully automated real-time
                    surveillance of messaging and chats and the end of privacy of
                    digital correspondence.
                </p>
                <p>
                    Other aspects of the proposal include ineffective network
                    blocking, screening of personal cloud storage including
                    private photos, mandatory age verification resulting in the
                    end of anonymous communication, appstore censorship and
                    excluding minors from the digital world.
                </p>
                <h2
                    class="text-2xl bg-yellow text-black border-b-3 border-black dark:border-white inline-block mt-2 mb-2 p-1"
                >
                    Chat Control 1.0
                </h2>
                <p>
                    On July 6, 2021, a majority of Members of the European
                    Parliament had already agreed to the voluntary use of chat
                    control (Chat Control 1.0). So far, only unencrypted US
                    communication services such as Gmail, Facebook/Instagram
                    Messenger, Skype, Snapchat, iCloud Mail, or Xbox make use of
                    this. In 2024, the EU adopted an extension of the voluntary
                    Chat Control 1.0 regulation by two years, until April 3,
                    2026. In March 2026, the European Parliament rejected a
                    second extension of the regulation, so that the interim
                    regulation expired on 4 April 2026. However, on 9 July 2026
                    the European Parliament allowed the suspicionless mass
                    scanning of private communications (“Chat Control 1.0”) to
                    pass, a measure it had rejected twice in March. Although a
                    majority of voting Members of the European Parliament (MEPs)
                    actually opposed the regulation (314 against, 276 in favor,
                    17 abstentions), the motion to reject it failed to secure
                    the required absolute majority of 361 votes. As a result,
                    mass scanning is now permitted again until 2028.
                </p>
                <p>
                    <span
                        class="bg-pink text-black border-b-2 border-black dark:border-white px-1"
                        >The fact that Chat Control is moving forward against
                        the will of the majority of voting MEPs is a farce and
                        damages democracy.</span
                    > It is also interesting that beforehand the actual vote, on
                    7 July this proposal was voted to be priority and be brought
                    to the parliament out of line. This is important since, they
                    definitely knew that during the summer season with a large portion
                    of MEPs being on leave, the absolute majority (361 MEPs) needed
                    to reject the law, would be way harder to gather. But hey, think
                    of the children!
                </p>
                <h2
                    class="text-2xl bg-yellow text-black border-b-3 border-black dark:border-white inline-block mt-2 mb-2 p-1"
                >
                    Chat Control 2.0
                </h2>
                <p>
                    On 11 May 2022 the European Commission presented a proposal
                    for a follow-up regulation for the mandatory use of chat
                    control by all providers and would even have applied to so
                    far securely end-to-end encrypted communication services
                    (Chat Control 2.0). A public consultation by the Commission
                    on this project had revealed that a majority of respondents,
                    both citizens and stakeholders, opposed imposing an
                    obligation to use indiscriminate message and chat control.
                    Over 80% of respondents opposed its application to
                    end-to-end encrypted communications. Parliament has
                    positioned itself almost unanimously against indiscriminate
                    chat control in 2023. Following protests, mandatory chat
                    control was finally removed also from the EU governments’
                    draft law late 2025.
                </p>
                <p>So as of today, 2026. 08. 03, the followings are true:</p>
                <ul class="list-[square] list-inside pl-4 mb-4 space-y-2">
                    <li>
                        US tech companies are once again allowed to scan private
                        messages without a warrant or prior suspicion. This
                        affects direct messages on platforms like Instagram,
                        Discord, Snapchat, Skype, and Xbox, as well as emails
                        via Google’s Gmail and Apple’s iCloud.
                    </li>
                    <li>
                        Public social media posts and files hosted in cloud
                        storage could already be scanned without this exemption
                        law. Furthermore, private messages can, independently of
                        the regulation, always be reported by users, or
                        monitored by authorities using targeted, court-ordered
                        wiretapping under national law.
                    </li>
                </ul>
                <p>
                    It's not me or the critics who state that the effectiveness
                    of Chat Control is debatable; it is the EU Commission
                    itself. <a
                        href="https://eur-lex.europa.eu/legal-content/EN/TXT/PDF/?uri=CELEX:52025DC0740"
                        target="_blank"
                        class="bg-yellow text-black border-b-3 border-black dark:border-white hover:bg-white p-1"
                        >In their own report</a
                    >, after 4 years of Chat Control 1.0 being active, they
                    concluded there is not enough data to give a definitive
                    answer. It's not us who have to prove that it won't work
                    (yet we still do); it's the other way around, it is them who
                    should prove that it actually defends our children. In the
                    same report, we can see that in 2024,
                    <b
                        >only 36% of reports actually came from messaging and
                        chat applications.</b
                    > This is significantly lower than the year before, where it
                    was 61%. This indicates a trend where people harming the rights
                    of children are migrating to E2EE applications and other private
                    networks.
                </p>

                <p>
                    End-to-end encrypted messaging platforms are excluded from
                    Chat Control, following large public outrage against
                    breaking encryption.
                </p>
                <p>
                    So I raise the question: what's the whole point? The
                    criminals who should be prosecuted get away by using E2EE
                    applications, but commoners using soyware applications pay
                    the price with their privacy gone. I'm not saying that we
                    should extend Chat Control to E2EE messages, hell no. I'm
                    saying that we are being scammed. <b
                        >Are we trading in our privacy and future generations'
                        privacy for something that doesn't even work?</b
                    > Mass surveillance is being built, but with a purpose vastly
                    different from defending our children.
                </p>
                <p>
                    Chat Control also diverts funding and motivation away from
                    actual solutions against CSAM. There is no easy or universal
                    solution that preserves privacy and human rights while
                    simultaneously solving CSAM or terrorism. If someone tells
                    you otherwise, they are lying to you. Police forces already
                    suffer from all the false positives (reports which are not
                    actually CSAM), and to decrease the number of FPs, more
                    aggressive monitoring would be needed. However, even if FPs
                    are low, for example below 1%, in case of a million reports,
                    that would still mean 10,000 ordinary people who would be
                    investigated falsely. Without proper context your grandma
                    sending you your old childhood picture, where you don't have
                    any clothes on, your grandma might as well be flagged as
                    CSAM distributer.
                </p>

