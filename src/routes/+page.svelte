    <div class="flex flex-col justify-center gap-4 w-7/8 md:w-5/8 p-10">
        <h2 id="private_messaging" class="text-5xl md:text-6xl">
            Privacy-preserving communication
        </h2>
        <div class="flex flex-col md:flex-row gap-4">
            <div class="contents md:flex-col md:flex md:basis-1/2">
                <p>
                    Private messaging in a normal, democratic world <b
                        >should be the standard</b
                    >. Sadly, this is <b>not</b> the case.
                    <b>Most normie applications</b>
                    widely used by people are
                    <b>nowhere close to being private</b>. The bar is so low...
                    In a normal conversation, wouldn't anyone be weirded out if
                    someone else stood next to them,
                    <span
                        class="text-black bg-pink border-b-2 border-black dark:border-white px-1"
                        >listening and writing down everything they say?</span
                    >
                </p>
                <p>
                    Whenever you send a message on most applications, it works
                    via a <b>client-server model</b>. This means that your
                    client (likely your phone or computer) <b>sends</b> the
                    message first to a <b>server</b>
                    maintained by the service provider, and then the server will
                    forward it to the recipient's client. This is done so the two
                    communicating clients don't have to be online all the time to
                    receive messages. The <b>server stores and forwards</b> because
                    it is always online.
                </p>
                <p>
                    Common network protocols nowadays implement <b>encryption</b
                    >
                    layers, which are cryptographically proven to guarantee that
                    only the two network devices, in this case, the server and your
                    client, can actually understand the messages. However, without
                    any further transformations,
                    <span
                        class="text-black bg-yellow border-b-2 border-black dark:border-white px-1"
                        >the server can still read the messages.</span
                    >
                    <b
                        >Your soyware applications like Facebook, Gmail,
                        Instagram, Snapchat, and so on do exactly that.</b
                    >
                </p>
                <div
                    class="card bg-sky-300 mb-5 text-black dark:bg-sky-800 dark:text-white"
                >
                    <button class="btn bg-pink mb-3"> TLS </button>
                    <p>
                        Transport Layer Security is an application-agnostic
                        security layer that enables two communicating sockets
                        (call them endpoints to simplify things) to have secure
                        communication, guaranteeing <b
                            >confidentiality and integrity</b
                        >. It utilizes asymmetric cryptography to establish a
                        shared secret between the endpoints, and then continues
                        with symmetric cryptography to encrypt the communication
                        using the established secret.
                    </p>
                </div>
                <p>
                    <b>We can't really trust the server.</b> Server
                    administrators can be
                    <b>bribed, compelled, or blackmailed,</b> and the companies
                    holding these servers really don't care about privacy at
                    all, unless that's their whole business model, like Signal.
                    In math we trust, so researchers built protocols made out of
                    cryptographically secure primitives for secure, encrypted
                    communications between clients. This way,
                    <b>the server can only see random gibberish</b>, and only
                    the sender and the recipient actually see the messages. We
                    call this communication <b>end-to-end encrypted</b> (E2EE).
                    In this scenario, it doesn't matter if the server has
                    malicious intent;
                    <span
                        class="bg-pink text-black border-b-2 border-black dark:border-white px-1"
                        >the universe would go cold before they could break the
                        encryption</span
                    > securing the communication.
                </p>
            </div>
            <div class="basis-1/2">
                <p>
                    We have E2EE, so we are all safe now, right? Not exactly. We
                    still have to trust and take the word of the service
                    providers that they actually implement a secure E2EE
                    protocol without any backdoors for nation-states, companies,
                    or anyone else. One way they could prove there is no sketchy
                    stuff in their application is if they open-sourced it and
                    made the whole messaging transparent. This way, anyone,
                    including security researchers, would be able to verify that
                    it is indeed secure. But guess what? That is not the case.
                    Most companies are <b>strictly closed-source</b> because they
                    want to keep their code base a secret from competitors. When
                    you use closed-source software, you are betting that this one
                    company is better at security than the entire world's security
                    community. That's a big gamble. Even if the company isn't evil
                    to the bone, they would still comply with secret government court
                    orders without letting you know, of course.
                </p>
                <div
                    class="card bg-rose-300 mb-5 text-black dark:bg-rose-800 dark:text-white"
                >
                    <button class="btn bg-pink mb-3">Skype backdoor</button>
                    <p>
                        Leaked NSA documents state that multiple US companies,
                        for example, Microsoft, collaborated with the agency,
                        providing backdoors to their services. In the case of
                        Skype, this meant that Microsoft helped the NSA
                        circumvent the encryption behind it, enabling access to
                        people's conversations. Communications could be
                        collected <b>without a warrant</b> if the NSA operative was
                        51% sure the suspect was a foreign citizen. You can't make
                        this shit up.
                    </p>
                </div>
                <p>
                    There is no universal solution to privacy-preserving
                    communication, since the problem itself is complex and has
                    multiple parameters. What's the best application out there
                    to communicate privately? It depends. There are multiple
                    solutions that suck way less than the mainstream
                    applications used by the general populace. In cybersecurity,
                    the term <i>threat model</i> is commonly used to assess what
                    an attacker is capable of with plausible reason. Based on
                    this threat model, multiple risks arise, and a defender has
                    to linearly match the risks with the amount of effort put
                    into countermeasures. For example, regarding communication,
                    your grandma and a political activist or journalist would
                    have vastly different threat models. However, I think we
                    should not forget that
                    <span
                        class="bg-yellow text-black border-b-2 border-black dark:border-white px-1"
                        >privacy is a non-negotiable human right.</span
                    > It's not like your grandma should have less privacy just because
                    there is a smaller chance someone else will try to breach it.
                    This is especially true in the world we live in, where untargeted
                    surveillance is a constantly returning topic. I won't compare
                    private communication methods here, since there are already plenty
                    of better-written comparisons out there, but I will argue why
                    I started using XMPP.
                </p>
            </div>
